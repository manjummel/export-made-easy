"""
contract_loader.py — ExportEase Knowledge API Contract Loader

Responsibilities:
  1. Load the shared OpenAPI contract from EXPORTEASE_CONTRACTS_PATH.
  2. If the local path is missing or the version does not match, fall back
     to cloning from EXPORTEASE_CONTRACTS_GIT_URL.
  3. Validate the contract using openapi-spec-validator.
  4. Expose a singleton via get_contract() for use anywhere in the service.

The contract is the single source of truth for:
  - Request/response schema validation
  - Contract tests (generated by schemathesis)
  - Version negotiation with System 1 consumers
"""

from __future__ import annotations

import hashlib
import logging
import os
import shutil
import tempfile
from pathlib import Path
from typing import Any

import yaml
from openapi_spec_validator import validate
from openapi_spec_validator.readers import read_from_filename
from tenacity import retry, stop_after_attempt, wait_fixed

logger = logging.getLogger(__name__)

# ── Module-level singleton ────────────────────────────────────────────────────
_contract_cache: dict[str, Any] | None = None
_contract_hash: str | None = None


class ContractLoadError(Exception):
    """Raised when the API contract cannot be loaded or validated."""


class ContractVersionMismatch(Exception):
    """Raised when the contract version does not match the expected API version."""


class ContractLoader:
    """
    Loads and validates the ExportEase Knowledge API contract (OpenAPI 3.1).

    Priority order:
      1. Local file at EXPORTEASE_CONTRACTS_PATH/knowledge_api_v1.yaml
      2. Git clone from EXPORTEASE_CONTRACTS_GIT_URL (fallback)
    """

    CONTRACT_FILENAME = "knowledge_api_v1.yaml"

    def __init__(
        self,
        contracts_path: str | None = None,
        git_url: str | None = None,
        git_branch: str | None = None,
        expected_api_version: str | None = None,
    ) -> None:
        self.contracts_path = Path(
            contracts_path
            or os.environ.get("EXPORTEASE_CONTRACTS_PATH", "/app/contracts")
        )
        self.git_url = git_url or os.environ.get(
            "EXPORTEASE_CONTRACTS_GIT_URL", ""
        )
        self.git_branch = git_branch or os.environ.get(
            "EXPORTEASE_CONTRACTS_GIT_BRANCH", "main"
        )
        self.expected_api_version = expected_api_version or os.environ.get(
            "KNOWLEDGE_API_VERSION", "v1"
        )

    # ── Public API ────────────────────────────────────────────────────────────

    def load(self) -> dict[str, Any]:
        """
        Load, validate, and return the contract spec as a dict.
        Caches the result for the lifetime of the process.
        """
        global _contract_cache, _contract_hash

        if _contract_cache is not None:
            logger.debug("Returning cached contract")
            return _contract_cache

        spec = self._load_local()
        if spec is None:
            logger.warning(
                "Contract not found at local path %s — attempting Git fallback",
                self.contracts_path,
            )
            spec = self._load_from_git()

        if spec is None:
            raise ContractLoadError(
                f"Could not load contract from {self.contracts_path} "
                f"or Git URL {self.git_url}"
            )

        self._validate_spec(spec)
        self._check_version(spec)

        raw_yaml = yaml.dump(spec, default_flow_style=False)
        _contract_hash = "sha256:" + hashlib.sha256(raw_yaml.encode()).hexdigest()[:16]
        _contract_cache = spec

        logger.info(
            "Contract loaded successfully — version=%s hash=%s",
            spec.get("info", {}).get("version", "unknown"),
            _contract_hash,
        )
        return spec

    def get_hash(self) -> str:
        """Return the SHA-256 hash prefix of the loaded contract."""
        if _contract_hash is None:
            self.load()
        return _contract_hash or "unloaded"

    def invalidate_cache(self) -> None:
        """Force the next load() call to re-read from disk/git."""
        global _contract_cache, _contract_hash
        _contract_cache = None
        _contract_hash = None
        logger.info("Contract cache invalidated")

    def validate_contract_version(self) -> bool:
        """
        Returns True if the contract version matches expected_api_version.
        Raises ContractVersionMismatch otherwise.
        """
        spec = self.load()
        self._check_version(spec)
        return True

    # ── Private helpers ───────────────────────────────────────────────────────

    def _load_local(self) -> dict[str, Any] | None:
        contract_file = self.contracts_path / self.CONTRACT_FILENAME
        if not contract_file.exists():
            logger.debug("Local contract file not found: %s", contract_file)
            return None

        logger.info("Loading contract from local path: %s", contract_file)
        try:
            spec_dict, _ = read_from_filename(str(contract_file))
            return spec_dict
        except Exception as exc:
            logger.error("Failed to read local contract file: %s", exc)
            return None

    @retry(stop=stop_after_attempt(3), wait=wait_fixed(2))
    def _load_from_git(self) -> dict[str, Any] | None:
        if not self.git_url:
            logger.warning("No EXPORTEASE_CONTRACTS_GIT_URL configured — skipping Git fallback")
            return None

        try:
            import git  # GitPython

            tmp_dir = tempfile.mkdtemp(prefix="exportease-contracts-")
            logger.info(
                "Cloning contracts from %s (branch: %s) into %s",
                self.git_url,
                self.git_branch,
                tmp_dir,
            )
            git.Repo.clone_from(
                self.git_url,
                tmp_dir,
                branch=self.git_branch,
                depth=1,
            )

            cloned_file = Path(tmp_dir) / self.CONTRACT_FILENAME
            if not cloned_file.exists():
                logger.error(
                    "Contract file %s not found in cloned repo", self.CONTRACT_FILENAME
                )
                return None

            # Copy into the contracts_path so next restart finds it locally
            self.contracts_path.mkdir(parents=True, exist_ok=True)
            shutil.copy(cloned_file, self.contracts_path / self.CONTRACT_FILENAME)
            logger.info("Contract saved to %s", self.contracts_path / self.CONTRACT_FILENAME)

            spec_dict, _ = read_from_filename(str(cloned_file))
            return spec_dict

        except Exception as exc:
            logger.error("Git clone failed: %s", exc)
            raise

    def _validate_spec(self, spec: dict[str, Any]) -> None:
        try:
            validate(spec)
            logger.debug("Contract OpenAPI validation passed")
        except Exception as exc:
            raise ContractLoadError(f"Contract validation failed: {exc}") from exc

    def _check_version(self, spec: dict[str, Any]) -> None:
        contract_version = spec.get("info", {}).get("version", "")
        # Accept "1.0.0" when expected_api_version is "v1"
        major = f"v{contract_version.split('.')[0]}" if contract_version else ""
        if self.expected_api_version not in (contract_version, major):
            raise ContractVersionMismatch(
                f"Contract version '{contract_version}' does not match "
                f"expected API version '{self.expected_api_version}'"
            )


# ── Module-level singleton accessor ──────────────────────────────────────────
_loader_instance: ContractLoader | None = None


def get_contract() -> dict[str, Any]:
    """
    Module-level convenience function — load and return the contract singleton.
    Safe to call multiple times; result is cached.
    """
    global _loader_instance
    if _loader_instance is None:
        _loader_instance = ContractLoader()
    return _loader_instance.load()


def get_contract_hash() -> str:
    """Return the hash of the currently loaded contract."""
    global _loader_instance
    if _loader_instance is None:
        _loader_instance = ContractLoader()
    return _loader_instance.get_hash()
